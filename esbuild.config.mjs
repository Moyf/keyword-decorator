import esbuild from "esbuild";
import { builtinModules } from "node:module";
import process from "process";
import { access, copyFile, mkdir } from "node:fs/promises";
import path from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const distDir = "dist";

async function copyStaticAssets() {
  const assets = ["manifest.json", "styles.css"];
  await mkdir(distDir, { recursive: true });

  for (const asset of assets) {
    const source = path.join(process.cwd(), asset);
    const target = path.join(process.cwd(), distDir, asset);

    try {
      await access(source);
      await copyFile(source, target);
    } catch (error) {
      if (asset === "manifest.json") {
        throw error;
      }
    }
  }
}

// Obsidian's official review and release tooling expects the bundle at the
// repository root, next to manifest.json and styles.css. Keep dist/ for the
// local Hot Reload flow and mirror main.js to the root in production builds.
async function copyBundleToRoot() {
  if (!prod) return;
  await copyFile(path.join(process.cwd(), distDir, "main.js"), path.join(process.cwd(), "main.js"));
}

esbuild
  .build({
    banner: {
      js: banner,
    },
    minify: prod ? true : false,
    charset: "utf8",
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
      "obsidian",
      "electron",
      "codemirror",
      "@codemirror/autocomplete",
      "@codemirror/closebrackets",
      "@codemirror/collab",
      "@codemirror/commands",
      "@codemirror/comment",
      "@codemirror/fold",
      "@codemirror/gutter",
      "@codemirror/highlight",
      "@codemirror/history",
      "@codemirror/language",
      "@codemirror/lint",
      "@codemirror/matchbrackets",
      "@codemirror/panel",
      "@codemirror/rangeset",
      "@codemirror/rectangular-selection",
      "@codemirror/search",
      "@codemirror/state",
      "@codemirror/stream-parser",
      "@codemirror/tooltip",
      "@codemirror/view",
      "@lezer/common",
      "@lezer/lr",
      "@lezer/highlight",
      ...builtinModules,
    ],
    format: "cjs",
    watch: !prod,
    target: "es2018",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "dist/main.js",
    plugins: [
      {
        name: "copy-static-assets",
        setup(build) {
          build.onEnd(async result => {
            if (result.errors.length > 0) {
              return;
            }
            await copyStaticAssets();
            await copyBundleToRoot();
          });
        },
      },
    ],
  })
  .catch(() => process.exit(1));
