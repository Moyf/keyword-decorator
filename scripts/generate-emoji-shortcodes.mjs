import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

// Input: github/gemoji db/emoji.json at the commit documented in THIRD-PARTY-NOTICES.md.
// This offline generator is not part of normal builds or plugin startup.
if (!process.argv[2]) throw new Error("Pass the path to gemoji's db/emoji.json.");
const entries = JSON.parse(readFileSync(process.argv[2], "utf8"));
const aliases = Object.create(null);
for (const entry of entries) {
  if (typeof entry.emoji !== "string" || !Array.isArray(entry.aliases)) continue;
  for (const alias of entry.aliases) {
    if (typeof alias === "string" && /^[a-z0-9_+-]+$/.test(alias)) aliases[alias] = entry.emoji;
  }
}
// A friendly KWD alias; gemoji's canonical equivalent is :smile:.
aliases.happy = aliases.smile;
const sorted = Object.fromEntries(Object.entries(aliases).sort(([left], [right]) => left.localeCompare(right, "en")));
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/emoji/data.ts");
const notice = readFileSync(resolve(root, "THIRD-PARTY-NOTICES.md"), "utf8").trim();
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `/*!\n${notice}\n*/\n// Generated by scripts/generate-emoji-shortcodes.mjs.\nexport const EMOJI_SHORTCODES: Readonly<Record<string, string>> = ${JSON.stringify(sorted)};\n`);
console.log(`Generated ${Object.keys(sorted).length} emoji aliases (${Buffer.byteLength(JSON.stringify(sorted))} bytes of UTF-8 data).`);
